# bot/exceptions.py

class AppError(Exception):
    """
    Базовое исключение приложения.
    Все кастомные ошибки должны наследоваться от него.
    """
    pass


# ------------------------------------------------------------
# ACCESS / PERMISSION
# ------------------------------------------------------------
class ForbiddenError(AppError):
    """
    Доступ запрещён (роль, смена, права).
    """
    def __init__(self, message: str = "Доступ запрещён"):
        super().__init__(message)


# ------------------------------------------------------------
# NOT FOUND
# ------------------------------------------------------------
class NotFoundError(AppError):
    """
    Сущность не найдена (заказ, позиция, пользователь и т.д.).
    """
    def __init__(self, message: str = "Объект не найден"):
        super().__init__(message)


# ------------------------------------------------------------
# STATE / FLOW
# ------------------------------------------------------------
class InvalidStateError(AppError):
    """
    Некорректное состояние объекта или FSM.
    """
    def __init__(self, message: str = "Некорректное состояние"):
        super().__init__(message)


# ------------------------------------------------------------
# VALIDATION
# ------------------------------------------------------------
class ValidationError(AppError):
    """
    Ошибка валидации входных данных.
    """
    def __init__(self, message: str = "Ошибка валидации данных"):
        super().__init__(message)


# ------------------------------------------------------------
# BUSINESS LOGIC
# ------------------------------------------------------------
class BusinessLogicError(AppError):
    """
    Нарушение бизнес-логики (лимиты, правила, условия).
    """
    def __init__(self, message: str = "Ошибка бизнес-логики"):
        super().__init__(message)

